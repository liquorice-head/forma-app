import Foundation
import Observation

@MainActor @Observable final class UIStrings {
    static let shared = UIStrings()
    static let systemLanguage = "system"
    private let defaults: UserDefaults
    private let readPreferredLanguages: () -> [String]
    private var preferredLanguages: [String]
    // Keep the existing stored values so a previous manual choice survives upgrades.
    var language: String {
        didSet { defaults.set(language, forKey: "prototype.language") }
    }

    init(defaults: UserDefaults = .standard, preferredLanguages: @escaping () -> [String] = { Locale.preferredLanguages }) {
        self.defaults = defaults
        readPreferredLanguages = preferredLanguages
        self.preferredLanguages = preferredLanguages()
        let saved = defaults.string(forKey: "prototype.language")
        language = saved.flatMap { [Self.systemLanguage, "Русский", "English"].contains($0) ? $0 : nil } ?? Self.systemLanguage
    }

    var effectiveLanguage: String {
        if language == "Русский" || language == "English" { return language }
        for identifier in preferredLanguages {
            switch Locale.Language(identifier: identifier).languageCode?.identifier {
            case "ru": return "Русский"
            case "en": return "English"
            default: continue
            }
        }
        return "English"
    }
    var isEnglish: Bool { effectiveLanguage == "English" }

    func refreshSystemLanguage() { preferredLanguages = readPreferredLanguages() }

    func translate(_ text: String) -> String { isEnglish ? Self.english[text] ?? text : text }

